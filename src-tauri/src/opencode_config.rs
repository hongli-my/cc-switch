const STANDARD_OMO_PLUGIN_PREFIXES: [&str; 2] = ["oh-my-openagent", "oh-my-opencode"];
const SLIM_OMO_PLUGIN_PREFIXES: [&str; 1] = ["oh-my-opencode-slim"];

fn matches_plugin_prefix(plugin_name: &str, prefix: &str) -> bool {
    plugin_name == prefix
        || plugin_name
            .strip_prefix(prefix)
            .map(|suffix| suffix.starts_with('@'))
            .unwrap_or(false)
}

fn matches_any_plugin_prefix(plugin_name: &str, prefixes: &[&str]) -> bool {
    prefixes
        .iter()
        .any(|prefix| matches_plugin_prefix(plugin_name, prefix))
}

fn canonicalize_plugin_name(plugin_name: &str) -> String {
    if let Some(suffix) = plugin_name.strip_prefix("oh-my-opencode") {
        if suffix.is_empty() || suffix.starts_with('@') {
            return format!("oh-my-openagent{suffix}");
        }
    }
    plugin_name.to_string()
}

pub fn get_opencode_dir() -> PathBuf {
    if let Some(override_dir) = get_opencode_override_dir() {
        return override_dir;
    }

    crate::config::get_home_dir()
        .join(".config")
        .join("opencode")
}

pub fn get_opencode_config_path() -> PathBuf {
    get_opencode_dir().join("opencode.json")
}

/// 获取 OpenCode SQLite 数据库路径
/// 优先级: OPENCODE_DB 环境变量 > XDG_DATA_HOME > ~/.local/share/opencode
pub fn get_opencode_db_path() -> PathBuf {
    // 支持 OPENCODE_DB 环境变量覆盖（忽略空字符串）
    if let Ok(custom_path) = std::env::var("OPENCODE_DB") {
        if !custom_path.is_empty() {
            let path = PathBuf::from(&custom_path);
            if path.is_absolute() {
                return path;
            }
            // 相对路径基于数据目录
            return get_opencode_data_dir().join(path);
        }
    }

    get_opencode_data_dir().join("opencode.db")
}

/// 发现所有 opencode profile 的数据库路径。
/// 返回 (profile_name, db_path) 列表。第一个永远是默认 profile（name 为空字符串）。
/// 命名 profile 通过扫描 <data_dir>/profiles/*/opencode.db 发现。
///
/// profiles 目录从默认 db 路径的 parent 推导（例如
/// `~/.local/share/opencode/opencode.db` → `~/.local/share/opencode/profiles/`）。
/// 当 `OPENCODE_DB` 指向自定义路径时，profiles 仍从该路径的 parent/profiles 扫描。
pub fn discover_opencode_profile_dbs() -> Vec<(String, PathBuf)> {
    let default_db = get_opencode_db_path();
    // 第一个永远是默认 profile（name 为空字符串），即使文件尚未创建也保留，
    // 便于调用方按统一路径处理（sync 函数内部会再判存在性）。
    let mut result = vec![(String::new(), default_db.clone())];

    // profiles 目录：从默认 db 路径的 parent 推导
    let profiles_dir = match default_db.parent() {
        Some(p) => p.join("profiles"),
        None => return result,
    };

    // 扫描 profiles/*/ 子目录；目录不存在等错误静默处理
    let entries = match std::fs::read_dir(&profiles_dir) {
        Ok(e) => e,
        Err(_) => return result,
    };

    for entry in entries.flatten() {
        let path = entry.path();
        // 只处理子目录
        if !path.is_dir() {
            continue;
        }
        // 只收录含 opencode.db 文件的子目录（自动跳过 *-shm / *-wal）
        let profile_db = path.join("opencode.db");
        if profile_db.is_file() {
            // profile 名 = 子目录名
            if let Some(name) = path.file_name().and_then(|n| n.to_str()) {
                result.push((name.to_string(), profile_db));
            }
        }
    }

    result
}

/// 发现所有 opencode profile 名（用于 skill 分发目标）。
///
/// 扫描 `<config_dir>/profiles/*/` 子目录名。第一个元素永远是默认 profile
/// （name 为空串 `""`，对应 `~/.config/opencode/skills/`），其后是排序后的
/// 命名 profile。profiles 目录不存在等错误静默返回 `vec!["".to_string()]`。
///
/// 注意：这里扫描的是 **config 目录**（`get_opencode_dir()`，受 settings.json
/// override_dir 影响），与 `discover_opencode_profile_dbs`（扫描 data 目录）
/// 不同——OpenCode 的 profile 在 config 与 data 两侧都用同名子目录。
pub fn discover_opencode_config_profiles() -> Vec<String> {
    let config_dir = get_opencode_dir();
    // 第一个永远是默认 profile（name 为空串），即使 profiles 目录不存在也保留
    let mut result = vec![String::new()];

    let profiles_dir = config_dir.join("profiles");

    // 扫描 profiles/*/ 子目录；目录不存在等错误静默处理
    let entries = match std::fs::read_dir(&profiles_dir) {
        Ok(e) => e,
        Err(_) => return result,
    };

    let mut named: Vec<String> = Vec::new();
    for entry in entries.flatten() {
        let path = entry.path();
        if !path.is_dir() {
            continue;
        }
        if let Some(name) = path.file_name().and_then(|n| n.to_str()) {
            // 跳过隐藏目录（如 .DS_Store 产物）
            if !name.is_empty() && !name.starts_with('.') {
                named.push(name.to_string());
            }
        }
    }

    named.sort();
    result.extend(named);
    result
}

fn get_opencode_data_dir() -> PathBuf {
    // 尊重 XDG_DATA_HOME（按 XDG 规范，空字符串视为未设置）
    if let Ok(xdg_data) = std::env::var("XDG_DATA_HOME") {
        if !xdg_data.is_empty() {
            return PathBuf::from(xdg_data).join("opencode");
        }
    }

    // OpenCode 使用 xdg-basedir，不遵守 macOS/Windows 平台约定，
    // 所有平台默认都落在 ~/.local/share/opencode
    crate::config::get_home_dir()
        .join(".local")
        .join("share")
        .join("opencode")
}

#[allow(dead_code)]
pub fn get_opencode_env_path() -> PathBuf {
    get_opencode_dir().join(".env")
}

pub fn read_opencode_config() -> Result<Value, AppError> {
    let path = get_opencode_config_path();

    if !path.exists() {
        return Ok(json!({
            "$schema": "https://opencode.ai/config.json"
        }));
    }

    let content = std::fs::read_to_string(&path).map_err(|e| AppError::io(&path, e))?;
    json5::from_str(&content).map_err(|e| {
        AppError::Config(format!(
            "Failed to parse OpenCode config: {}: {e}",
            path.display()
        ))
    })
}

pub fn write_opencode_config(config: &Value) -> Result<(), AppError> {
    let path = get_opencode_config_path();
    write_json_file(&path, config)?;

    log::debug!("OpenCode config written to {path:?}");
    Ok(())
}

pub fn get_providers() -> Result<Map<String, Value>, AppError> {
    let config = read_opencode_config()?;
    Ok(config
        .get("provider")
        .and_then(|v| v.as_object())
        .cloned()
        .unwrap_or_default())
}

pub fn set_provider(id: &str, config: Value) -> Result<(), AppError> {
    let mut full_config = read_opencode_config()?;

    if full_config.get("provider").is_none() {
        full_config["provider"] = json!({});
    }

    if let Some(providers) = full_config
        .get_mut("provider")
        .and_then(|v| v.as_object_mut())
    {
        providers.insert(id.to_string(), config);
    }

    write_opencode_config(&full_config)
}

pub fn remove_provider(id: &str) -> Result<(), AppError> {
    let mut config = read_opencode_config()?;

    if let Some(providers) = config.get_mut("provider").and_then(|v| v.as_object_mut()) {
        providers.remove(id);
    }

    write_opencode_config(&config)
}

pub fn get_typed_providers() -> Result<IndexMap<String, OpenCodeProviderConfig>, AppError> {
    let providers = get_providers()?;
    let mut result = IndexMap::new();

    for (id, value) in providers {
        match serde_json::from_value::<OpenCodeProviderConfig>(value.clone()) {
            Ok(config) => {
                result.insert(id, config);
            }
            Err(e) => {
                log::warn!("Failed to parse provider '{id}': {e}");
            }
        }
    }

    Ok(result)
}

pub fn set_typed_provider(id: &str, config: &OpenCodeProviderConfig) -> Result<(), AppError> {
    let value = serde_json::to_value(config).map_err(|e| AppError::JsonSerialize { source: e })?;
    set_provider(id, value)
}

